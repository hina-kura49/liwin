//! Guards the frozen D-Bus protocol: the introspection XML of `Daemon1` and
//! `ShellBridge1` must match `tests/introspection.xml`.
//!
//! After an intended protocol change (and a `docs/dbus.md` update), refresh
//! the snapshot with `LIWIN_BLESS=1 cargo test --test introspection`.

mod common;

use std::path::Path;

use common::*;
use liwin_daemon::{BRIDGE_INTERFACE, DAEMON_INTERFACE, Options};

/// Drops XML comments (zbus may emit doc comments) and whitespace between
/// tags, and puts every tag on its own line.
fn normalize(xml: &str) -> String {
    let mut rest = xml;
    let mut out = String::new();
    while let Some(start) = rest.find("<!--") {
        out.push_str(&rest[..start]);
        let end = rest[start..].find("-->").expect("unterminated comment") + start + 3;
        rest = &rest[end..];
    }
    out.push_str(rest);
    out.split('<')
        .map(|chunk| chunk.split_whitespace().collect::<Vec<_>>().join(" "))
        .filter(|chunk| !chunk.is_empty())
        .map(|chunk| format!("<{chunk}"))
        .collect::<Vec<_>>()
        .join("\n")
}

fn extract_interface(xml: &str, name: &str) -> String {
    let open = format!("<interface name=\"{name}\">");
    let start = xml
        .find(&open)
        .unwrap_or_else(|| panic!("{name} missing from introspection:\n{xml}"));
    let end = xml[start..].find("</interface>").unwrap() + start + "</interface>".len();
    xml[start..end].to_owned()
}

#[tokio::test]
async fn introspection_matches_the_snapshot() {
    let bus = Bus::start().await;
    let _daemon = bus.daemon(Options::default()).await;
    let client = bus.connect().await;
    let xml: String = call(
        &client,
        "org.freedesktop.DBus.Introspectable",
        "Introspect",
        &(),
    )
    .await
    .unwrap();

    let actual = [DAEMON_INTERFACE, BRIDGE_INTERFACE]
        .iter()
        .map(|name| normalize(&extract_interface(&xml, name)))
        .collect::<Vec<_>>()
        .join("\n")
        + "\n";

    let path = Path::new(env!("CARGO_MANIFEST_DIR")).join("tests/introspection.xml");
    if std::env::var_os("LIWIN_BLESS").is_some() {
        let header = "<!-- SPDX-License-Identifier: MIT OR Apache-2.0 -->\n\
            <!-- Generated by tests/introspection.rs (LIWIN_BLESS=1). -->\n";
        std::fs::write(&path, format!("{header}{actual}")).unwrap();
        return;
    }
    let expected = std::fs::read_to_string(&path).unwrap();
    assert_eq!(
        normalize(&expected),
        normalize(&actual),
        "the D-Bus protocol changed; update docs/dbus.md and re-bless {}",
        path.display()
    );
}
